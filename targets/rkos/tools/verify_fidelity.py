#!/usr/bin/env python3
"""Provenance, ledger accounting, and Hex-Rays anti-idiom verifier for `targets/rkos/`."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

COMMENT_OR_STRING_RE = re.compile(
    r"//[^\n]*|/\*.*?\*/|\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'",
    re.DOTALL,
)

BANNED_IDIOM_RE = re.compile(
    r"\b(?:HIWORD|LOWORD|LODWORD|HIDWORD|"
    r"BYTE[0-9]+|SBYTE[0-9]+|WORD[0-9]+|SWORD[0-9]+|DWORD[0-9]+|"
    r"__PAIR64__|__PAIR32__|__OFSUB__|__CFADD__|__CFSUB__|__get_CPSR|"
    r"COERCE_FLOAT|COERCE_UNSIGNED_INT)\b|"
    r"\bgoto\s+LABEL_[0-9A-Za-z_]*\b|"
    r"\b(?:v[1-9][0-9]*|a[1-9][0-9]*)\b"
)

SHIM_RE = re.compile(r"/\*\s*@shim\s+RVA\s+(0x[0-9a-fA-F]+)\s+(\S+)")
PROVENANCE_RE = re.compile(r"/\*\s*@provenance\s+RVA\s+(0x[0-9a-fA-F]+)\s+(\S+)\s*\*/")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."), help="Target root (`targets/rkos`)")
    parser.add_argument("--output", type=Path, default=None, help="Optional JSON report path")
    args = parser.parse_args()

    root = args.root.resolve()
    inv_path = root / "verification/inventory.json"
    led_path = root / "verification/ledger.json"
    inv = json.loads(inv_path.read_text(encoding="utf-8"))
    led = json.loads(led_path.read_text(encoding="utf-8"))

    errors: list[str] = []

    # 1. Scan C and H files (excluding generated byte-array .inc files) for banned idioms
    scan_files = sorted(
        list((root / "src").rglob("*.c"))
        + list((root / "include").rglob("*.h"))
        + list((root / "tests").rglob("*.c"))
        + list((root / "tests").rglob("*.h"))
    )
    idiom_violations: list[dict[str, object]] = []
    for fpath in scan_files:
        raw_txt = fpath.read_text(encoding="utf-8")
        cleaned = COMMENT_OR_STRING_RE.sub(lambda m: "\n" * m.group(0).count("\n"), raw_txt)
        for lineno, line in enumerate(cleaned.splitlines(), start=1):
            for match in BANNED_IDIOM_RE.finditer(line):
                idiom_violations.append({
                    "file": str(fpath.relative_to(root)),
                    "line": lineno,
                    "token": match.group(0),
                })
    if idiom_violations:
        errors.append(f"found {len(idiom_violations)} banned Hex-Rays idiom token(s)")

    # 2. Extract @provenance tags across src/ and cross-check inventory & ledger
    inv_by_rva = {int(f["rva"], 16): f for f in inv["functions"]}
    led_by_rva = {int(f["rva"], 16): f for f in led["functions"]}

    if len(inv["functions"]) != 864 or len(inv_by_rva) != 864:
        errors.append(f"inventory function count mismatch: {len(inv['functions'])}")
    if len(led["functions"]) != 864 or len(led_by_rva) != 864:
        errors.append(f"ledger function count mismatch: {len(led['functions'])}")
    if set(inv_by_rva.keys()) != set(led_by_rva.keys()):
        errors.append("inventory and ledger RVA sets do not match 1:1")

    seen_prov: dict[int, tuple[str, str]] = {}
    for cfile in sorted((root / "src").rglob("*.c")):
        rel = str(cfile.relative_to(root))
        txt = cfile.read_text(encoding="utf-8")
        if "shims/" in rel and "@provenance" in txt:
            errors.append(f"shim file {rel} must not carry @provenance tags")
        for m in SHIM_RE.finditer(txt):
            srva = int(m.group(1), 16)
            if srva not in led_by_rva or led_by_rva[srva].get("classification") != "pending_c":
                errors.append(f"@shim RVA {hex(srva)} in {rel} must be classified pending_c")
        for m in PROVENANCE_RE.finditer(txt):
            rva = int(m.group(1), 16)
            ida_name = m.group(2)
            if rva in seen_prov:
                errors.append(f"duplicate @provenance RVA {hex(rva)} in {rel} and {seen_prov[rva][1]}")
            seen_prov[rva] = (ida_name, rel)
            if rva not in inv_by_rva:
                errors.append(f"@provenance RVA {hex(rva)} in {rel} missing from inventory.json")
            elif inv_by_rva[rva]["name"] != ida_name:
                errors.append(
                    f"@provenance name mismatch at {hex(rva)}: {ida_name} vs {inv_by_rva[rva]['name']}"
                )

    ledger_rec_rvas = {
        int(f["rva"], 16) for f in led["functions"] if f.get("classification") == "reconstructed_c"
    }
    ledger_ret_rvas = {
        int(f["rva"], 16) for f in led["functions"] if f.get("classification") == "retained_native"
    }
    ledger_pend_rvas = {
        int(f["rva"], 16) for f in led["functions"] if f.get("classification") == "pending_c"
    }

    if set(seen_prov.keys()) != ledger_rec_rvas:
        missing = sorted(hex(x) for x in (ledger_rec_rvas - set(seen_prov.keys())))
        extra = sorted(hex(x) for x in (set(seen_prov.keys()) - ledger_rec_rvas))
        errors.append(f"@provenance vs ledger reconstructed_c mismatch: missing={missing} extra={extra}")

    if len(ledger_rec_rvas) + len(ledger_ret_rvas) + len(ledger_pend_rvas) != 864:
        errors.append("ledger classifications do not partition all 864 functions")

    passed = len(errors) == 0
    report = {
        "target": "rkos",
        "files_scanned": len(scan_files),
        "idiom_violations": idiom_violations,
        "inventory_functions": len(inv_by_rva),
        "reconstructed_c": len(ledger_rec_rvas),
        "retained_native": len(ledger_ret_rvas),
        "pending_c": len(ledger_pend_rvas),
        "errors": errors,
        "passed": passed,
    }

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    if not passed:
        for err in errors:
            print(f"[verify_fidelity] FAIL: {err}", file=sys.stderr)
        for v in idiom_violations[:10]:
            print(f"  violation: {v}", file=sys.stderr)
        return 1

    print(
        f"[verify_fidelity] PASS: {len(scan_files)} files clean, "
        f"{len(ledger_rec_rvas)} reconstructed_c + {len(ledger_ret_rvas)} retained_native + "
        f"{len(ledger_pend_rvas)} pending_c = 864/864 functions accounted"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
